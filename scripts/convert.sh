#!/usr/bin/env bash
# Regenerate spl/<rule>.spl for every Sigma rule file (sigma-cli, Splunk backend).
#
# Pipelines, in order:
#   sysmon                           generic categories (process_creation, ...) -> Sysmon EventIDs;
#                                    a no-op for rules on service: security / system
#   pipelines/splunk_windows_xml.yml source="WinEventLog:..." OR "XmlWinEventLog:...", EventID -> EventCode
#
# One rule file = one query. A correlation file carries its base rule(s) in the same file
# (multi-document YAML), so sigma-cli resolves the references and prints only the correlation.
#
# Generated files are never edited by hand. `./scripts/convert.sh --check` fails on drift (CI).
set -euo pipefail
cd "$(dirname "$0")/.."
check=false
[[ "${1:-}" == "--check" ]] && check=true
status=0
version="$(sigma version | cut -d' ' -f1)"
for rule in detections/*/*/rules/*.yml; do
  dir="$(dirname "$(dirname "$rule")")"
  name="$(basename "$rule" .yml)"
  out="$dir/spl/$name.spl"
  query="$(sigma convert -t splunk -p sysmon -p pipelines/splunk_windows_xml.yml "$rule" | sed '/^Parsing Sigma rules/d')"
  content="# Generated by scripts/convert.sh from rules/$name.yml - do not edit.
# sigma-cli $version, backend splunk, pipelines: sysmon, pipelines/splunk_windows_xml.yml
# Prepend your index or macro, e.g. \`windows_security\` <query> or index=<your_index> <query>
$query"
  if $check; then
    if ! diff -q <(printf '%s\n' "$content") "$out" >/dev/null 2>&1; then
      echo "DRIFT: $out (run ./scripts/convert.sh)"; status=1
    fi
  else
    mkdir -p "$dir/spl"
    printf '%s\n' "$content" > "$out"
    echo "wrote $out"
  fi
done
exit $status
